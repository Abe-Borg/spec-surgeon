"""Synthetic Word workloads for reproducible engine evaluation, never client evidence.

The named cases are stable acceptance categories, not claims of Word visual coverage.
Both compared runs use the same generated bytes. No provider or renderer is called.
"""
from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt


CASES = (
    "ordinary", "typed-headings", "styled-headings", "direct-formatting", "automatic-list",
    "table", "header-footer", "unicode", "repeated-provisions", "tracked-insertion",
    "multiple-sections", "blank-paragraphs",
)


def build_corpus(folder):
    folder.mkdir(parents=True)
    paths = []
    for index, name in enumerate(CASES):
        doc = Document()
        doc.add_paragraph("SECTION 21 13 13 – WET-PIPE SPRINKLER SYSTEMS")
        if name == "styled-headings":
            doc.add_paragraph("PART 1 GENERAL", "Heading 1")
            doc.add_paragraph("1.1 SUMMARY", "Heading 2")
        else:
            doc.add_paragraph("PART 1 GENERAL")
            doc.add_paragraph("1.1 SUMMARY")
        p = doc.add_paragraph("A. Provide wet-pipe sprinkler systems.")
        if name == "direct-formatting":
            p.runs[0].bold = True
            p.runs[0].font.size = Pt(13)
        elif name == "automatic-list":
            doc.add_paragraph("Include valves and fittings.", "List Number")
        elif name == "table":
            table = doc.add_table(rows=2, cols=2)
            table.cell(0, 0).text = "Material"
            table.cell(0, 1).text = "Requirement"
            table.cell(1, 0).text = "Steel"
            table.cell(1, 1).text = "ASTM A53"
        elif name == "header-footer":
            doc.sections[0].header.paragraphs[0].text = "PROJECT NORTH"
            doc.sections[0].footer.paragraphs[0].text = "21 13 13"
        elif name == "unicode":
            doc.add_paragraph("Provide ½-inch fittings; façade zone A–B; 20 °C.")
        elif name == "repeated-provisions":
            doc.add_paragraph("B. Provide 4-inch pipe.")
            doc.add_paragraph("C. Provide 6-inch pipe.")
        elif name == "tracked-insertion":
            ins = OxmlElement("w:ins")
            ins.set(qn("w:id"), "7")
            ins.set(qn("w:author"), "Synthetic fixture")
            ins.set(qn("w:date"), "2026-10-18T00:00:00Z")
            run, text = OxmlElement("w:r"), OxmlElement("w:t")
            text.text = " Include approved test valves."
            run.append(text)
            ins.append(run)
            p._p.append(ins)
        elif name == "multiple-sections":
            doc.add_section()
            doc.add_paragraph("PART 2 PRODUCTS")
        elif name == "blank-paragraphs":
            doc.add_paragraph()
            doc.add_paragraph()
        doc.add_paragraph("END OF SECTION")
        path = folder / f"{index + 1:02d}-{name}.docx"
        doc.save(path)
        paths.append(path)
    return paths


